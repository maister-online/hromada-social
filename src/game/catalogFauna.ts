import { Fauna3DBodyShape, Fauna3DModelSpec, FishSpeciesDef, LocationId } from './types';

function inferBodyShape(sp: FishSpeciesDef): Fauna3DBodyShape {
  if (sp.faunaKind === 'crayfish') return 'crayfish';
  if (sp.faunaKind === 'beetle') return 'beetle';
  if (sp.faunaKind === 'insect') return 'insect';
  if (sp.faunaKind === 'wildlife') {
    const id = sp.id;
    if (id.includes('frog') || id.includes('toad') || id.includes('tadpole')) return 'frog';
    if (id.includes('turtle') || id.includes('snail') || id.includes('mussel')) return 'turtle';
    if (id.includes('leech')) return 'leech';
    if (id.includes('snake')) return 'snake';
    if (id.includes('spider')) return 'insect';
    return 'eel';
  }
  const key = sp.silhouetteKey;
  if (key === 'sterlet' || key === 'leviathan_polissia') return 'sturgeon';
  if (key === 'catfish' || key === 'catfish_glow' || key === 'burbot' || key === 'barbel') {
    return 'catfish';
  }
  if (key === 'eel' || key === 'swamp_eel') return 'eel';
  if (
    key === 'crucian' ||
    key === 'crucian_glow' ||
    key === 'bream' ||
    key === 'carp' ||
    key === 'carp_mutant'
  ) {
    return 'deep';
  }
  return 'fusiform';
}

function enrichFauna(sp: FishSpeciesDef): FishSpeciesDef {
  const kind = sp.faunaKind ?? (sp.isMutant ? 'mutant' : 'fish');
  const sizeClass =
    sp.sizeClass ??
    (sp.maxWeightKg >= 12
      ? 'trophy'
      : sp.maxWeightKg >= 4
        ? 'large'
        : sp.maxWeightKg >= 1.2
          ? 'medium'
          : 'small');

  const default3d: Fauna3DModelSpec = sp.model3d ?? {
    bodyShape: inferBodyShape({ ...sp, faunaKind: kind }),
    primaryHex: sp.accentColor,
    secondaryHex: sp.isMutant ? '#0f292e' : '#1e293b',
    finHex: sp.isMutant ? '#22d3ee' : sp.accentColor,
    eyeCount: sp.isMutant ? 3 : 2,
    hasClaws: kind === 'crayfish',
    glowHex: sp.isMutant ? sp.accentColor : undefined,
    armorPlates: sp.id.includes('armored') || sp.id === 'carp_mutant',
    electricArcs: sp.id.includes('electric') || sp.id === 'zander_crystal' || sp.id === 'swamp_eel',
    scaleFactor: sizeClass === 'trophy' ? 1.45 : sizeClass === 'large' ? 1.18 : sizeClass === 'small' ? 0.72 : 1.0,
  };

  return {
    ...sp,
    faunaKind: kind,
    sizeClass,
    habitat:
      sp.habitat ??
      (sp.preferredDepth === 'bottom'
        ? 'Донні ями та бровки'
        : sp.preferredDepth === 'surface'
          ? 'Поверхневі перекати та плесо'
          : 'Водна товща й прибережні зарості'),
    behavior:
      sp.behavior ??
      (sp.fightPower >= 7.5
        ? 'Могутні ривки, тисне вагою в глибину'
        : sp.fightPower >= 4.5
          ? 'Активний опір із боковими кидками'
          : 'Швидкі дрібні потяжки'),
    model3d: default3d,
  };
}

